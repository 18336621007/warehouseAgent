# Evaluator 评估模块配置 —— 评分权重、阈值、时间映射

# 综合评分权重（总和 = 1.0）
WEIGHT_TIME = 0.2       # 话题总耗时
WEIGHT_TURNS = 0.2      # Advisor 追问轮次
WEIGHT_LLM_SELF = 0.4   # LLM 自评（语义连贯性 + 需求满足度）
WEIGHT_USER = 0.2       # 用户显式评分

# 高质量对话阈值：≥ 此分数的对话入库作为示例
HIGH_QUALITY_THRESHOLD = 80

# 用户默认评分（未打分时的中性值）
DEFAULT_USER_SCORE = 75

# ── 时间分数映射：总耗时(ms) → 0~100 分数 ──
# 设计原因：非线性映射。快速响应(<10s)给高分，超慢(>120s)给低分但不归零。
# 因为"慢"可能因为数据量大，不代表答案差。
TIME_SCORE_MAP = [
    (5000, 100),       # ≤ 5s：满分
    (10000, 90),       # 5~10s
    (20000, 80),       # 10~20s
    (30000, 70),       # 20~30s
    (60000, 60),       # 30~60s
    (120000, 40),      # 60~120s
    (600000, 20),      # >120s：最低 20 分（保留底线）
]

# ── 轮次分数映射：Advisor 追问轮次 → 0~100 分数 ──
# 设计原因：轮次越少越高效。但 0 轮（直接 Seeker）并不意味着最好，
# 因为可能漏掉了该问的问题。1~2 轮澄清是合理区间。
TURN_SCORE_MAP = [
    (1, 100),          # 1 轮澄清即确认：最佳
    (2, 85),           # 2 轮：良好
    (3, 70),           # 3 轮：可接受
    (5, 50),           # 4~5 轮：偏多
    (10, 30),          # 6~10 轮：过多
    (float("inf"), 10),# >10 轮：接近失败
]


def map_value_to_score(value, score_map):
    """根据分段映射表，将数值映射为 0~100 分数"""
    for threshold, score in score_map:
        if value <= threshold:
            return score
    return score_map[-1][1]  # 兜底：取最后一档分数
